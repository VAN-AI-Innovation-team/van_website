export const conferenceEditionRoutes = conferenceEditions.map(({ year, slug }) => ({
  key: 'conferenceEdition',
  navKey: 'conference',
  kind: 'edition',
  slug: `conference/${slug}`,
  year,
}))

export function getConferenceEdition(year, lang = 'ko') {
  const source = conferenceEditions.find((edition) => edition.year === String(year))
  if (!source) return null

  return {
    id: source.id,
    year: source.year,
    slug: source.slug,
    publicationStatus: source.publicationStatus,
    structuredEvent: source.structuredEvent,
    statusLabel: getConferenceStatusLabel(lang, source.publicationStatus),
    ...source.localized[lang],
  }
}

export function getConferenceEditionSummaries(lang = 'ko') {
  return conferenceEditions
    .map(({ year }) => getConferenceEdition(year, lang))
    .filter(Boolean)
    .sort((left, right) => Number(right.year) - Number(left.year))
}

export function getConferenceStatusLabel(lang, status) {
  const labels = {
    ko: {
      confirmed: '확정',
      published: '공개',
      archived: '지난 행사',
      development: '개발 중',
    },
    en: {
      confirmed: 'Confirmed',
      published: 'Published',
      archived: 'Past conference',
      development: 'In development',
    },
  }

  return labels[lang]?.[status] || labels[lang]?.development || labels.en.development
}
